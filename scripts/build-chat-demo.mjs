import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

// Bundle only the local policy and approved text. No provider code or credentials.
export function demoBundle() {
  const knowledge = readFileSync(new URL('../server/knowledge.mjs', import.meta.url), 'utf8').replaceAll('export ', '');
  const policy = readFileSync(new URL('../server/policy.mjs', import.meta.url), 'utf8').split('const intents =')[0].replace(/^import .*;\r?\n/, '').replaceAll('export ', '');
  return `// Generated by scripts/build-chat-demo.mjs. Edit the approved source files instead.\n(() => {\n${knowledge}\n${policy}\nwindow.PepcisionChatDemo = Object.freeze({ reply(message) {
  if (typeof message !== 'string' || !message.trim() || message.length > 1000) throw new Error('Enter a message of 1–1,000 characters.');
  const decision = localDecision(message);
  if (!decision && /^(hi|hello|hey|thanks|thank you)[!.?]*$/i.test(message.trim())) return { answer: 'Hello! This is the Pepcision demo. Try Shipping, Availability, Order support, or a documentation question. Replies are preset; there is no live AI or order access.', source: null };
  return renderDecision(decision || { action: 'escalated' });
} });\n})();\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) writeFileSync(new URL('../chat/demo.js', import.meta.url), demoBundle());
